class Lv2Stage(hk.Module):
  """Level-2 evaluation stage owning all level-2 children of an lv3 term."""

  def __init__(self, parent_shape: np.ndarray, name: str = 'lv2_stage'):
    super().__init__(name=name)
    self._lv2_shapes = prepare_shapes(level=2)
    self.num_lv2 = self._lv2_shapes.shape[0]

    shape_types, rotate_nums = [], []
    for i in range(self.num_lv2):
      st, rn = _compute_shape_type_and_rotation(self._lv2_shapes[i])
      shape_types.append(st)
      rotate_nums.append(rn)
    self.shape_types = jnp.array(shape_types, dtype=jnp.int32)
    self.rotate_nums = jnp.array(rotate_nums, dtype=jnp.int32)

    splits = prepare_splits(parent_shape)
    self.num_split = splits.shape[0]
    self.splits_left = splits[:, :3]
    self.splits_right = splits[:, 3:]

    lv2_shape_list = [tuple(s) for s in self._lv2_shapes]
    lv2_to_idx = {s: i for i, s in enumerate(lv2_shape_list)}

    left_mask = np.zeros((self.num_split, self.num_lv2), dtype=np.float32)
    right_mask = np.zeros((self.num_split, self.num_lv2), dtype=np.float32)
    left_idx = np.zeros(self.num_split, dtype=int)
    right_idx = np.zeros(self.num_split, dtype=int)
    for i in range(self.num_split):
      li = lv2_to_idx[tuple(self.splits_left[i])]
      ri = lv2_to_idx[tuple(self.splits_right[i])]
      left_mask[i, li] = 1.0
      right_mask[i, ri] = 1.0
      left_idx[i] = li
      right_idx[i] = ri
    self.left_mask = jnp.array(left_mask)
    self.right_mask = jnp.array(right_mask)
    self.scatter_mask = self.left_mask + self.right_mask
    self.left_idx = left_idx
    self.right_idx = right_idx

    referenced = np.sum(left_mask + right_mask, axis=0) > 0
    self.referenced_mask = jnp.array(referenced)

    self.split_0: jax.Array | None = None
    self.term_frac: jax.Array | None = None
    self.num_block_contribution: jax.Array | None = None
    self.mat_size_contribution: jax.Array | None = None
    self.complete_split: jax.Array | None = None

  def __call__(self):
    logits = hk.get_parameter(
        'split_0',
        [6, 6, self.num_lv2],
        init=hk.initializers.RandomUniform(-2.89, 1.50),
    )
    logits = logits * self.referenced_mask[None, None, :]
    flat_st = jnp.tile(self.shape_types, 36)
    flat_logits = logits.reshape(-1)
    self.split_0 = _evaluate_init_lv2_batch(flat_st, flat_logits).reshape(
        6, 6, self.num_lv2
    )
    self.term_frac = jnp.zeros((6, 6, self.num_lv2))

  def evaluate_post(self, log_q: float):
    assert self.split_0 is not None
    assert self.term_frac is not None
    s0_flat = self.split_0.reshape(-1)
    tf_flat = self.term_frac.reshape(-1)
    flat_st = jnp.tile(self.shape_types, 36)
    flat_rn = jnp.tile(self.rotate_nums, 36)
    nb_all, ms_all, cs_all = _evaluate_post_lv2_batch(
        flat_st,
        flat_rn,
        s0_flat,
        tf_flat,
        log_q,
    )
    self.num_block_contribution = nb_all.reshape(6, 6, self.num_lv2, 3)
    self.mat_size_contribution = ms_all.reshape(6, 6, self.num_lv2, 3)
    self.complete_split = cs_all.reshape(6, 6, self.num_lv2, 3, 9)


