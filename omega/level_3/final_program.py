class Workspace(hk.Module):
  """Top-level Haiku module assembling the full omega upper-bound model."""

  def __init__(self, q, K, num_sinkhorn_iterations, name='workspace'):
    super().__init__(name=name)
    self.q, self.K = q, K
    self.gs = GlobalStage(
        q=q, K=K, num_sinkhorn_iterations=num_sinkhorn_iterations
    )
    # Adaptive aggregation parameters for different parts of the loss.
    # Initialized with RandomUniform around the previous constant values
    # to encourage diversity.
    self.eps_l_nrg = hk.get_parameter(
        'eps_l_nrg', (6,), init=hk.initializers.RandomUniform(-8.0, -7.0)
    )
    self.mix_l_nrg = hk.get_parameter(
        'mix_l_nrg', (6,), init=hk.initializers.RandomUniform(-1.5, -0.5)
    )
    self.eps_l_nr_lv3 = hk.get_parameter(
        'eps_l_nr_lv3', (6,), init=hk.initializers.RandomUniform(-8.0, -7.0)
    )
    self.mix_l_nr_lv3 = hk.get_parameter(
        'mix_l_nr_lv3', (6,), init=hk.initializers.RandomUniform(-1.5, -0.5)
    )
    self.eps_l_nc2 = hk.get_parameter(
        'eps_l_nc2', (), init=hk.initializers.RandomUniform(-8.0, -7.0)
    )
    self.mix_l_nc2 = hk.get_parameter(
        'mix_l_nc2', (), init=hk.initializers.RandomUniform(-1.5, -0.5)
    )
    self.eps_l_sms = hk.get_parameter(
        'eps_l_sms', (), init=hk.initializers.RandomUniform(-8.0, -7.0)
    )
    self.mix_l_sms = hk.get_parameter(
        'mix_l_sms', (), init=hk.initializers.RandomUniform(-1.5, -0.5)
    )
    self.eps_l_retained = hk.get_parameter(
        'eps_l_retained', (), init=hk.initializers.RandomUniform(-8.0, -7.0)
    )
    self.mix_l_retained = hk.get_parameter(
        'mix_l_retained', (), init=hk.initializers.RandomUniform(-1.5, -0.5)
    )

  def _agg(self, v, e_param, m_param):
    e, m = jax.nn.softplus(e_param), jax.nn.sigmoid(m_param)
    e_b = e
    if e.ndim < v.ndim:
      e_b = jnp.expand_dims(e, -1)
    mv = (1 - m) * (-e * special.logsumexp(v / -e_b, -1)) + m * jnp.mean(v, -1)
    return mv + jax.lax.stop_gradient(jnp.min(v, -1) - mv), 1e-2 * jnp.std(
        v, -1
    )

  def __call__(self):
    gs = self.gs
    gs()
    gs.evaluate_pre()
    lq, ts = math.log(self.q), gs.lv3_terms

    # Prepare adaptive aggregation parameters for each call site
    e_nrg, m_nrg = self.eps_l_nrg, self.mix_l_nrg
    e_nr_lv3, m_nr_lv3 = self.eps_l_nr_lv3, self.mix_l_nr_lv3
    e_nc2, m_nc2 = self.eps_l_nc2, self.mix_l_nc2
    e_sms, m_sms = self.eps_l_sms, self.mix_l_sms
    e_ret, m_ret = self.eps_l_retained, self.mix_l_retained
    for t in ts:
      t.evaluate_post(lq)
    gs.lv3_zero.evaluate_post(lq)
    gs.evaluate_post(lq)
    agg = lambda a: sum(getattr(t, a).sum(0) for t in ts)
    nb, hp, py, pz = [
        agg(a)
        for a in [
            'num_block_contribution',
            'hash_penalty_term',
            'p_compY',
            'p_compZ',
        ]
    ]
    d0, d1, d2 = _DIMS.T
    idx = jnp.arange(6)
    nrg, bg = self._agg(
        jnp.stack(
            [
                gs.num_block[idx, d0] - gs.hash_penalty_term,
                gs.num_block[idx, d1] - gs.p_compY,
                gs.num_block[idx, d2] - gs.p_compZ,
            ],
            -1,
        ),
        e_nrg,
        m_nrg,
    )
    nr_lv3, bl = self._agg(
        jnp.stack([nb[idx, d0] - hp, nb[idx, d1] - py, nb[idx, d2] - pz], -1),
        e_nr_lv3,
        m_nr_lv3,
    )
    nc2, bc = self._agg(
        sum(t.lv2.num_block_contribution.sum((0, 1, 2)) for t in ts),
        e_nc2,
        m_nc2,
    )
    sms, bm = self._agg(
        jnp.array([gs.mat_size[0], gs.mat_size[1], gs.mat_size[2] / self.K]),
        e_sms,
        m_sms,
    )
    retained_per_region = nrg + nr_lv3
    agg_retained, br = self._agg(retained_per_region, e_ret, m_ret)
    total_retained = 6 * agg_retained + nc2
    self.omega = (math.log(self.q + 2) * 4 - total_retained) / jnp.maximum(
        sms, 1e-7
    )
    prec = jnp.mean(
        jnp.stack(
            [jnp.max(t.derivative_upper_bound) for t in ts]
            + [jnp.max(gs.derivative_upper_bound)]
        )
    )
    return self.omega + jnp.sum(bg) + jnp.sum(bl) + bc + bm + br + 0.1 * prec, {
        'loss_omega': self.omega
    }


