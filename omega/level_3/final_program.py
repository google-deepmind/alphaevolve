def init_params(
    q: float, K: float, num_sinkhorn_iterations: int, seed: int = 0
) -> hk.Params:
  """Initialises a single set of Haiku parameters for the omega bound model."""
  return hk.transform(_forward).init(
      jax.random.PRNGKey(seed),
      q=q,
      K=K,
      num_sinkhorn_iterations=num_sinkhorn_iterations,
  )


def init_params_batch(
    q: float,
    K: float,
    num_sinkhorn_iterations: int,
    num_seeds: int,
    seed_offset: int = 0,
) -> hk.Params:
  """Initialises a batch of Haiku parameters across multiple random seeds."""
  keys = jax.vmap(jax.random.PRNGKey)(
      jnp.arange(seed_offset, seed_offset + num_seeds)
  )
  return jax.vmap(
      functools.partial(
          hk.transform(_forward).init,
          q=q,
          K=K,
          num_sinkhorn_iterations=num_sinkhorn_iterations,
      )
  )(keys)


@functools.partial(jax.jit, static_argnums=(1, 2, 3))
def differentiable_omega_upper_bound(
    params: hk.Params, q: float, K: float, num_sinkhorn_iterations: int
) -> jax.Array:
  """Evaluates the differentiable omega upper bound for given parameters."""
  return hk.transform(_forward).apply(
      params, None, q, K, num_sinkhorn_iterations
  )


