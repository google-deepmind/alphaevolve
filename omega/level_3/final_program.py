def _evaluate_init_term_info_zero_step_t(
    complete_split_id_t: jax.Array,
    complete_split_params_t: jax.Array,
    power: int,
) -> jax.Array:
  logits = jnp.zeros(3**power, dtype=float)
  logits = jnp.where(complete_split_id_t == -1, -jnp.inf, logits)
  logits = jnp.where(complete_split_id_t == -2, 0.0, logits)
  logits = jnp.where(complete_split_id_t >= 0, complete_split_params_t, logits)
  return special.softmax(logits)


_evaluate_init_term_info_zero = jax.jit(
    jax.vmap(_evaluate_init_term_info_zero_step_t, in_axes=(0, 0, None)),
    static_argnums=(2,),
)


@jax.jit
def _evaluate_post_term_info_zero(
    split_vec: jax.Array,
    ones_counts: jax.Array,
    log_q: float,
    term_frac: jax.Array,
    base_mat_size: jax.Array,
) -> jnp.ndarray:
  inner_prod_size = entropy(split_vec)
  inner_prod_size += jnp.dot(split_vec, ones_counts) * log_q
  return term_frac * inner_prod_size * base_mat_size


