class Lv3ZeroStage(hk.Module):
  """One module for all zero-containing level-3 shapes."""

  def __init__(self, name: str = 'lv3_zero_stage'):
    super().__init__(name=name)
    all_shapes = prepare_shapes(level=_MAX_LEVEL)
    power = 2 ** (_MAX_LEVEL - 1)
    self.power = power
    zero_mask = np.min(all_shapes, axis=1) == 0
    self.zero_indices = np.where(zero_mask)[0]
    self.num_zero = len(self.zero_indices)
    self.zero_shapes = all_shapes[self.zero_indices]

    self.zero_dim = np.zeros(self.num_zero, dtype=int)
    self.nonzero_dim_1 = np.zeros(self.num_zero, dtype=int)
    self.nonzero_dim_2 = np.zeros(self.num_zero, dtype=int)
    self.base_mat_size = np.zeros((self.num_zero, 3), dtype=float)
    ones_counts_list = []
    complete_split_id_list = []

    for zi in range(self.num_zero):
      shape = self.zero_shapes[zi]
      if shape[0] == 0:
        zd, nd1, nd2 = 0, 1, 2
        bms = np.array([0, 0, 1], dtype=float)
      elif shape[1] == 0:
        zd, nd1, nd2 = 1, 0, 2
        bms = np.array([1, 0, 0], dtype=float)
      else:
        zd, nd1, nd2 = 2, 0, 1
        bms = np.array([0, 1, 0], dtype=float)
      self.zero_dim[zi] = zd
      self.nonzero_dim_1[zi] = nd1
      self.nonzero_dim_2[zi] = nd2
      self.base_mat_size[zi] = bms

      cs_id = np.ones((3, 3**power), dtype=int) * -1
      cs_id[zd][0] = -2
      ones_counts = np.zeros(3**power, dtype=float)
      for idx in range(3**power):
        arr = decode_csd(idx + 1, power)
        ones_counts[idx] = np.sum(arr == 1)
        if np.sum(arr) != shape[nd1]:
          continue
        opp_idx = 3**power - 1 - idx
        cs_id[nd1][idx] = 1
        cs_id[nd2][opp_idx] = 2
      complete_split_id_list.append(cs_id)
      ones_counts_list.append(ones_counts)

    self.complete_split_id = jnp.array(
        np.stack(complete_split_id_list), dtype=jnp.int32
    )
    self.ones_counts = jnp.array(np.stack(ones_counts_list))
    self.base_mat_size_jnp = jnp.array(self.base_mat_size)

    self.complete_split: jax.Array | None = None
    self.term_frac: jax.Array | None = None
    self.mat_size_contribution: jax.Array | None = None

  def __call__(self):
    cs_raw_params = hk.get_parameter(
        'cs_params',
        [6, self.num_zero, 3**self.power],
        init=hk.initializers.RandomUniform(-10.0, 0.0),
    )
    id_expanded = self.complete_split_id[None, ...]
    cs_expanded = cs_raw_params[:, :, None, :]
    cs_opposite = cs_raw_params[:, :, None, ::-1]

    complete_split = jnp.where(
        id_expanded == -1,
        -jnp.inf,
        jnp.where(
            id_expanded == -2,
            0.0,  # was 1.0 in unnormalized probs, and this is a logit
            jnp.where(id_expanded == 1, cs_expanded, cs_opposite),
        ),
    )
    self.complete_split = jax.nn.softmax(complete_split, axis=-1)
    self.term_frac = jnp.zeros((6, self.num_zero))

  def evaluate_post(self, log_q: float):
    assert self.complete_split is not None
    assert self.term_frac is not None
    zi_idx = jnp.arange(self.num_zero)
    split_vecs = self.complete_split[:, zi_idx, self.nonzero_dim_1]
    _batch_zi = jax.vmap(
        _evaluate_post_term_info_zero, in_axes=(0, 0, None, 0, 0)
    )
    _batch_r_zi = jax.vmap(_batch_zi, in_axes=(0, None, None, 0, None))
    self.mat_size_contribution = _batch_r_zi(
        split_vecs,
        self.ones_counts,
        log_q,
        self.term_frac,
        self.base_mat_size_jnp,
    )


