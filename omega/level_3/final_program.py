def optimize_omega(
    q: float,
    K: float,
    num_steps: int = 32000,
    learning_rate: float = 1e-3,
    num_sinkhorn_iterations: int = 5,
    seed: int = 0,
    num_seeds: int = 1,
):
  """Runs gradient descent to minimise the omega upper bound."""
  params = init_params_batch(q, K, num_sinkhorn_iterations, num_seeds, seed)
  loss_fn = functools.partial(
      differentiable_omega_upper_bound,
      q=q,
      K=K,
      num_sinkhorn_iterations=num_sinkhorn_iterations,
  )
  loss_grad = jax.jit(jax.vmap(jax.value_and_grad(loss_fn, has_aux=True)))

  sched = optax.cosine_onecycle_schedule(
      num_steps, learning_rate, 0.3, 25.0, 1000.0
  )
  opt = optax.chain(
      optax.clip_by_global_norm(1.0),
      optax.adamw(sched, weight_decay=1e-4, b1=0.9, b2=0.99),
  )
  opt_state = jax.vmap(opt.init)(params)

  @jax.jit
  def step_fn(p, g, s):
    def f(p, g, s):
      u, ns = opt.update(g, s, p)
      return optax.apply_updates(p, u), ns

    return jax.vmap(f)(p, g, s)

  best_p, best_l = params, jnp.full(num_seeds, jnp.inf)

  for step in range(num_steps):
    (loss, ext), grads = loss_grad(params)
    imp = loss < best_l
    best_l = jnp.where(imp, loss, best_l)
    best_p = jax.tree.map(
        lambda bp, p, m=imp: jnp.where(
            m.reshape(-1, *[1] * (p.ndim - 1)), p, bp
        ),
        best_p,
        params,
    )
    if step % 100 == 0:
      print(
          f'Step {step} | best_omega = {float(jnp.min(ext["loss_omega"])):.8f}'
      )
    params, opt_state = step_fn(params, grads, opt_state)

  idx = jnp.argmin(best_l)
  best_p = jax.tree.map(lambda x: x[idx], best_p)
  omega = float(loss_fn(best_p)[0])
  print(f'Final loss: {float(best_l[idx]):.8f}, omega: {omega:.8f}')
  return best_p, float(best_l[idx]), omega


def get_hyper_sweep() -> list[dict[str, Any]]:
  """Returns the default hyperparameter configurations for optimisation."""
  return [
      {'num_sinkhorn_iterations': 120, 'learning_rate': 2.0e-2, 'num_seeds': 32}
  ]


