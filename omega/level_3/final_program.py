class Lv3TermInfo(hk.Module):
  """One module per non-zero level-3 shape."""

  def __init__(
      self,
      shape: np.ndarray,
      num_sinkhorn_iterations: int,
      name: str = 'lv3_term',
  ):
    super().__init__(name=name)
    self.shape = np.array(shape, dtype=int)
    self.num_sinkhorn_iterations = num_sinkhorn_iterations
    self.power = 2 ** (_MAX_LEVEL - 1)
    self.sum_half = int(np.sum(self.shape)) // 2

    self.lv2 = Lv2Stage(self.shape)

    splits = prepare_splits(self.shape)
    self.splits = splits
    self.num_split = splits.shape[0]
    self.joint_to_margin_mats = joint_to_margin(splits[:, :3], self.sum_half)

    self._pair_split_idx = np.repeat(np.arange(self.num_split), 2)
    self._pair_child_idx = np.column_stack(
        [self.lv2.left_idx, self.lv2.right_idx]
    ).ravel()
    pair_child_shapes = self.lv2._lv2_shapes[self._pair_child_idx]
    self._pair_child_shapes = pair_child_shapes
    self._pair_child_has_zero = np.min(pair_child_shapes, axis=1) == 0

    self.lam_margin_low = np.ones(3, dtype=int) * 999
    self.lam_margin_high = np.ones(3, dtype=int) * -999
    for row in splits:
      for t in range(3):
        self.lam_margin_low[t] = min(self.lam_margin_low[t], row[t])
        self.lam_margin_high[t] = max(self.lam_margin_high[t], row[t])
    self.lam_margin_low = self.lam_margin_low.astype(int)
    self.lam_margin_high = self.lam_margin_high.astype(int)
    self.max_lam_size = int(
        max(
            self.lam_margin_high[t] - self.lam_margin_low[t] + 1
            for t in range(3)
        )
    )
    self.lam_sizes = [
        int(self.lam_margin_high[t] - self.lam_margin_low[t] + 1)
        for t in range(3)
    ]

    self.region_prop: jax.Array | None = None
    self.split_dist: jax.Array | None = None
    self.split_dist_max: jax.Array | None = None
    self.lam_margin: jax.Array | None = None
    self.lam_sum: jax.Array | None = None
    self.derivative_upper_bound: jax.Array | None = None
    self.term_frac: jax.Array | None = None

    self.complete_split: jax.Array | None = None
    self.complete_split_region: jax.Array | None = None
    self.hash_penalty_term: jax.Array | None = None
    self.num_block_contribution: jax.Array | None = None
    self.mat_size_contribution: jax.Array | None = None
    self.p_compY: jax.Array | None = None
    self.p_compZ: jax.Array | None = None

  def __call__(self):
    self.region_prop = jax.vmap(special.softmax)(
        hk.get_parameter(
            'region_prop',
            [6, 6],
            init=hk.initializers.RandomUniform(-1.0, 1.0),
        )
    )
    self.split_dist = jax.vmap(jax.vmap(special.softmax))(
        hk.get_parameter(
            'split_dist',
            [6, 6, self.num_split],
            init=hk.initializers.RandomUniform(-1.0, 1.0),
        )
    )
    self.split_dist_max, self.lam_margin, self.lam_sum = jax.vmap(
        jax.vmap(_solve_max_entropy_sinkhorn, in_axes=(0, None, None)),
        in_axes=(0, None, None),
    )(self.split_dist, self.joint_to_margin_mats, self.num_sinkhorn_iterations)
    split_indices = self.splits[:, :3].T
    lam_at_splits = self.lam_margin[:, :, jnp.arange(3)[:, None], split_indices]
    vals = (
        jnp.sum(lam_at_splits, axis=2)
        + self.lam_sum[..., None]
        - 1.0
        - jnp.log(self.split_dist_max)
    )
    self.derivative_upper_bound = jnp.max(jnp.abs(vals), axis=-1)

    self.term_frac = jnp.zeros(6)
    self.lv2()

  def evaluate_pre(self):
    assert self.term_frac is not None
    assert self.split_dist is not None
    assert self.region_prop is not None
    frac = (
        self.term_frac[:, None, None]
        * self.split_dist
        * self.region_prop[:, :, None]
    )
    self.lv2.term_frac = jnp.einsum('ors,sl->orl', frac, self.lv2.scatter_mask)

  def evaluate_post(self, log_q: float):
    self.lv2.evaluate_post(log_q)
    assert self.lv2.complete_split is not None
    assert self.region_prop is not None
    assert self.split_dist is not None
    assert self.split_dist_max is not None

    left_cs = jnp.einsum(
        'sl,orltc->orstc', self.lv2.left_mask, self.lv2.complete_split
    )
    right_cs = jnp.einsum(
        'sl,orltc->orstc', self.lv2.right_mask, self.lv2.complete_split
    )
    cs_combined = jax.vmap(jax.vmap(jax.vmap(jax.vmap(concat_csd))))(
        left_cs, right_cs
    )

    self.complete_split_region = jnp.einsum(
        'ors,orstc->ortc', self.split_dist, cs_combined
    )
    self.complete_split = jnp.einsum(
        'or,ortc->otc', self.region_prop, self.complete_split_region
    )

    self.hash_penalty_term = (
        (
            jax.vmap(jax.vmap(entropy))(self.split_dist_max)
            - jax.vmap(jax.vmap(entropy))(self.split_dist)
            + 2 * self.derivative_upper_bound
        )
        * self.term_frac[:, None]
        * self.region_prop
    )

    all_dists = jax.vmap(
        jax.vmap(marginal_dist, in_axes=(0, None)),
        in_axes=(0, None),
    )(self.split_dist, self.joint_to_margin_mats)
    all_ent = jax.vmap(jax.vmap(jax.vmap(entropy)))(all_dists)
    self.num_block_contribution = (
        self.term_frac[:, None, None] * self.region_prop[:, :, None] * all_ent
    )
    self.mat_size_contribution = jnp.zeros(3)

    dims_y = _DIMS[:, 1]
    dims_z = _DIMS[:, 2]
    inner_rs = np.arange(6)

    csr_ent = jax.vmap(jax.vmap(jax.vmap(entropy)))(self.complete_split_region)
    den_all = csr_ent - all_ent
    pz_den = den_all[:, inner_rs, dims_z]
    py_den = den_all[:, inner_rs, dims_y]

    pz_num = self._pcomp_numerator(dims_z, None)
    py_num = self._pcomp_numerator(dims_y, dims_z)

    scale = self.term_frac[:, None] * self.region_prop
    self.p_compZ = (pz_num - pz_den) * scale
    self.p_compY = (py_num - py_den) * scale

  def _pcomp_numerator(
      self, target_dims: np.ndarray, entropy_dims: np.ndarray | None
  ):
    n_groups = self.sum_half + 1

    child_dim_size = self._pair_child_shapes[:, target_dims].T
    active = child_dim_size > 0
    if entropy_dims is None:
      use_ent = np.broadcast_to(
          self._pair_child_has_zero, (6, len(self._pair_child_has_zero))
      )
    else:
      use_ent = self._pair_child_shapes[:, entropy_dims].T == 0
    ent_mask = active & use_ent
    acc_mask = active & ~use_ent

    split_probs = self.split_dist[:, :, self._pair_split_idx]

    cs = self.lv2.complete_split[:, :, self._pair_child_idx]
    target_one_hot = jax.nn.one_hot(target_dims, 3)
    child_splits_target = jnp.einsum('oipdv,id->oipv', cs, target_one_hot)

    ent_vals = jax.vmap(jax.vmap(jax.vmap(entropy)))(child_splits_target)
    masked_split_probs_ent = split_probs * jnp.array(ent_mask)[None, :, :]
    res = jnp.sum(masked_split_probs_ent * ent_vals, axis=2)

    masked_split_probs_acc = split_probs * jnp.array(acc_mask)[None, :, :]
    contributions = masked_split_probs_acc[:, :, :, None] * child_splits_target

    group_one_hot = jax.nn.one_hot(child_dim_size, n_groups)
    weighted = jnp.einsum('oipv,ipg->goiv', contributions, group_one_hot)
    prob_sum = jnp.einsum('oip,ipg->goi', masked_split_probs_acc, group_one_hot)

    group_ent = jax.vmap(jax.vmap(jax.vmap(normalized_entropy)))(
        weighted[1:], prob_sum[1:]
    )
    res = res + jnp.sum(group_ent, axis=0)
    return res

  def _pcomp_denominator_vec(self, inner_r: int, dim: int):
    res = jax.vmap(entropy)(self.complete_split_region[:, inner_r, dim])
    dists = jax.vmap(marginal_dist, in_axes=(0, None))(
        self.split_dist[:, inner_r], self.joint_to_margin_mats
    )
    res = res - jax.vmap(entropy)(dists[:, dim])
    return res


