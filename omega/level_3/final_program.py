def entropy(arr: jnp.ndarray | float | np.ndarray) -> jnp.ndarray:
  """Computes the entropy of a discrete distribution."""
  x = jnp.asarray(arr, dtype=float)
  eps = jnp.finfo(float).eps
  return jnp.sum(-x * jnp.log(jnp.maximum(x, eps)))


@jax.jit
def normalized_entropy(arr: jnp.ndarray, p: float | jnp.ndarray) -> jnp.ndarray:
  """Computes the entropy of a sub-distribution normalized by total weight p."""
  p_val = jnp.asarray(p, dtype=float)
  val = jnp.clip(jnp.asarray(arr, dtype=float), 0.0, None)

  normalized = val / jnp.where(p_val > 0, p_val, 1.0)
  eps = jnp.finfo(float).eps
  result = jnp.sum(-val * jnp.log(jnp.maximum(normalized, eps)))

  return jnp.where(p_val > 0, result, 0.0)


