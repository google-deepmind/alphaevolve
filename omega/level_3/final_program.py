def safe_log(x: float | np.ndarray) -> np.ndarray:
  """Returns log(x), clamping x to avoid log(0)."""
  return np.log(np.maximum(x, np.finfo(float).tiny))


def convert_params_to_verification(
    params: hk.Params,
    q: float,
    K: float,
    num_sinkhorn_iterations: int,
) -> np.ndarray:
  """Convert Haiku optimisation_lv3 params to verification.py flat vector."""
  max_level = _MAX_LEVEL

  # Build the verification workspace
  ver_context = verification.create_context(
      q=q, max_level=max_level, K=K, use_term_sharing=False
  )
  ver_workspace = verification.Workspace(ver_context)
  ver_workspace.build(max_level=max_level)
  ver_param_manager = ver_context.param_manager
  ver_param_manager.random_init()
  ver_gs = ver_workspace.globstage
  assert ver_gs is not None

  globalstage_params = params['workspace/~/global_stage']
  lv3_zero_params = params['workspace/~/global_stage/~/lv3_zero_stage']

  # --- Map GlobalStage parameters ---
  region_prop_logits = np.array(globalstage_params['region_prop'])
  region_prop = scipy.special.softmax(region_prop_logits)
  ver_param_manager.set_single_param(ver_gs.region_prop_id, region_prop)

  dist_logits = np.array(globalstage_params['dist'])
  dist = scipy.special.softmax(dist_logits, axis=1)

  shapes = ver_gs.shapes
  sum_col = 2**max_level
  j2m_mats = joint_to_margin(shapes, sum_col)
  dist_max, lam_margin, lam_sum = jax.vmap(
      _solve_max_entropy_sinkhorn, in_axes=(0, None, None)
  )(jnp.array(dist), j2m_mats, num_sinkhorn_iterations)
  dist_max = np.array(dist_max)
  lam_margin = np.array(lam_margin)
  lam_sum = np.array(lam_sum)

  for r in range(6):
    ver_param_manager.set_single_param(ver_gs.dist_id[r], dist[r])
    ver_param_manager.set_single_param(ver_gs.dist_max_id[r], dist_max[r])

  for r in range(6):
    for t in range(3):
      ver_param_manager.set_single_param(
          ver_gs.lam_margin_id[r][t], lam_margin[r, t]
      )

  for r in range(6):
    ver_param_manager.set_single_param(ver_gs.lam_sum_id[r], [lam_sum[r]])

  for r in range(6):
    ver_param_manager.set_single_param(
        ver_gs.derivative_upper_bound_id[r], [1.0]
    )

  # --- Map TermInfoZero (lv3_zero) ---
  zero_cs_logits = np.array(
      lv3_zero_params['cs_params']
  )  # (6, num_zero, 3**power)
  zero_cs_log_probs = zero_cs_logits - scipy.special.logsumexp(
      zero_cs_logits, axis=-1, keepdims=True
  )
  num_zero = zero_cs_logits.shape[1]
  power = 2 ** (max_level - 1)

  shapes = ver_gs.shapes
  nonzero_mask = np.min(shapes, axis=1) > 0
  nonzero_indices = np.where(nonzero_mask)[0]
  zero_indices = np.where(~nonzero_mask)[0]

  for r in range(6):
    for zi in range(num_zero):
      ver_term = ver_gs.term_ptr[r][zero_indices[zi]]
      shape = shapes[zero_indices[zi]]
      if shape[0] == 0:
        nd1 = 1
      elif shape[1] == 0:
        nd1 = 0
      else:
        nd1 = 0

      for idx in range(3**power):
        arr = decode_csd(idx + 1, power)
        if np.sum(arr) == shape[nd1]:
          gid = ver_term.complete_split_id[nd1][idx]
          if gid >= 0:
            val = np.exp(zero_cs_log_probs[r, zi, idx])
            ver_param_manager.set_single_param(gid, [val])

  # --- Map TermInfo (lv3_term_i) ---
  for i, shape_idx in enumerate(nonzero_indices):
    term_params = params[f'workspace/~/global_stage/~/lv3_term_{i}']

    # region_prop: (6, 6) logits
    term_rp_logits = np.array(term_params['region_prop'])
    term_rp = scipy.special.softmax(term_rp_logits, axis=1)

    term_sd_logits = np.array(term_params['split_dist'])
    term_sd = scipy.special.softmax(term_sd_logits, axis=2)

    term_j2m_mats = joint_to_margin(
        prepare_splits(shapes[shape_idx])[:, :3],
        int(np.sum(shapes[shape_idx])) // 2,
    )
    term_sd_max, term_lam_margin, term_lam_sum = jax.vmap(
        jax.vmap(_solve_max_entropy_sinkhorn, in_axes=(0, None, None)),
        in_axes=(0, None, None),
    )(jnp.array(term_sd), term_j2m_mats, num_sinkhorn_iterations)
    term_sd_max = np.array(term_sd_max)
    term_lam_margin = np.array(term_lam_margin)
    term_lam_sum = np.array(term_lam_sum)

    for r in range(6):
      ver_term = ver_gs.term_ptr[r][shape_idx]

      ver_param_manager.set_single_param(ver_term.region_prop_id, term_rp[r])

      for inner_r in range(6):
        ver_param_manager.set_single_param(
            ver_term.split_dist_id[inner_r], term_sd[r, inner_r]
        )
        ver_param_manager.set_single_param(
            ver_term.split_dist_max_id[inner_r], term_sd_max[r, inner_r]
        )

      for inner_r in range(6):
        for t in range(3):
          low = int(ver_term.lam_margin_low[t])
          high = int(ver_term.lam_margin_high[t])
          ver_param_manager.set_single_param(
              ver_term.lam_margin_id[inner_r][t],
              term_lam_margin[r, inner_r, t, low : high + 1],
          )
        ver_param_manager.set_single_param(
            ver_term.lam_sum_id[inner_r], [term_lam_sum[r, inner_r]]
        )
        ver_param_manager.set_single_param(
            ver_term.derivative_upper_bound_id[inner_r], [1.0]
        )

  # --- Map TermInfoLv2 (lv2_stage inside lv3_term_i) ---
  for r in range(6):
    for i, shape_idx in enumerate(nonzero_indices):
      lv2_params = params[
          f'workspace/~/global_stage/~/lv3_term_{i}/~/lv2_stage'
      ]
      split_0_logits = np.array(lv2_params['split_0'])  # (6, 6, num_lv2)

      ver_term = ver_gs.term_ptr[r][shape_idx]
      num_split = ver_term.num_split

      for inner_r in range(6):
        for split_i in range(num_split):
          # Left child
          left_ptr = ver_term.left_ptr[inner_r][split_i]
          if (
              left_ptr is not None
              and getattr(left_ptr, 'split_0_id', None) is not None
          ):
            # left_idx is 1-based; not needed for the lv2 shape lookup.
            # To know which lv2 index this corresponds to in Haiku, we can use
            # the fact we map them sequentially in Haiku Lv2Stage.
            # Lv2Stage._lv2_shapes matches verification.py level 2
            # shapes.
            lv2_shape = left_ptr.shape
            # Find its index in _lv2_shapes (which is prepare_shapes(2))
            # lv2_shapes = prepare_shapes(2)
            # Find exact matching row:
            lv2_shapes = prepare_shapes(2)
            lv2_idx = np.where((lv2_shapes == lv2_shape).all(axis=1))[0][0]

            logit_s0 = float(split_0_logits[r, inner_r, lv2_idx])
            prob_dist = scipy.special.softmax(
                np.array([logit_s0, logit_s0, 0.0])
            )
            ver_param_manager.set_single_param(
                left_ptr.split_0_id, [prob_dist[0]]
            )

          # Right child
          right_ptr = ver_term.right_ptr[inner_r][split_i]
          if (
              right_ptr is not None
              and getattr(right_ptr, 'split_0_id', None) is not None
          ):
            lv2_shape = right_ptr.shape
            lv2_shapes = prepare_shapes(2)
            lv2_idx = np.where((lv2_shapes == lv2_shape).all(axis=1))[0][0]

            logit_s0 = float(split_0_logits[r, inner_r, lv2_idx])
            prob_dist = scipy.special.softmax(
                np.array([logit_s0, logit_s0, 0.0])
            )
            ver_param_manager.set_single_param(
                right_ptr.split_0_id, [prob_dist[0]]
            )

  # --- Map Workspace auxiliary variables ---
  for r in range(6):
    for inner_r in range(max_level + 1):
      # Try/catch or check if num_retain_comp_id exists
      if (
          len(ver_workspace.num_retain_comp_id[r]) > inner_r
          and ver_workspace.num_retain_comp_id[r][inner_r] is not None
      ):
        ver_param_manager.set_single_param(
            ver_workspace.num_retain_comp_id[r][inner_r], [0.01]
        )
  for r in range(6):
    ver_param_manager.set_single_param(
        ver_workspace.num_retain_glob_id[r], [0.01]
    )
  ver_param_manager.set_single_param(ver_workspace.single_mat_size_id, [0.01])
  ver_param_manager.set_single_param(ver_workspace.omega_id, [0.01])
  ver_param_manager.set_single_param(ver_workspace.K_id, [K])

  return ver_param_manager.cur_x.copy()


def convert_params_from_verification(
    x_vector: np.ndarray,
    q: float,
    K: float,
) -> hk.Params:
  """Convert verification.py flat vector to optimisation_lv3 params."""
  max_level = _MAX_LEVEL

  ver_ctx = verification.create_context(
      q=q, max_level=max_level, K=K, use_term_sharing=False
  )
  ver_ws = verification.Workspace(ver_ctx)
  ver_ws.build(max_level=max_level)
  ver_pm = ver_ctx.param_manager
  ver_pm.set_value(x_vector)
  ver_gs = ver_ws.globstage
  assert ver_gs is not None

  globalstage_key = 'workspace/~/global_stage'
  lv3_zero_key = 'workspace/~/global_stage/~/lv3_zero_stage'

  # --- GlobalStage ---
  region_prop_raw = ver_pm.get_param(ver_gs.region_prop_id)
  region_prop_logits = safe_log(region_prop_raw)

  dist_logits = np.zeros((6, ver_gs.num_shape), dtype=np.float64)
  for r in range(6):
    dist_logits[r] = safe_log(ver_pm.get_param(ver_gs.dist_id[r]))

  # --- TermInfoZero ---
  power = 2 ** (max_level - 1)

  shapes = ver_gs.shapes
  nonzero_mask = np.min(shapes, axis=1) > 0
  nonzero_indices = np.where(nonzero_mask)[0]
  zero_indices = np.where(~nonzero_mask)[0]

  num_zero = len(zero_indices)
  zero_cs_logits = np.zeros((6, num_zero, 3**power), dtype=np.float64)

  for r in range(6):
    for zi in range(num_zero):
      ver_term = ver_gs.term_ptr[r][zero_indices[zi]]
      shape = shapes[zero_indices[zi]]
      if shape[0] == 0:
        nd1 = 1
      elif shape[1] == 0:
        nd1 = 0
      else:
        nd1 = 0

      for idx in range(3**power):
        arr = decode_csd(idx + 1, power)
        if np.sum(arr) == shape[nd1]:
          gid = ver_term.complete_split_id[nd1][idx]
          if gid >= 0:
            val = ver_pm.get_param(gid).item()
            zero_cs_logits[r, zi, idx] = safe_log(val)

  new_params = {
      globalstage_key: {
          'region_prop': jnp.array(region_prop_logits),
          'dist': jnp.array(dist_logits),
      },
      lv3_zero_key: {
          'cs_params': jnp.array(zero_cs_logits),
      },
  }

  # --- TermInfo (lv3_term_i) ---
  lv2_shapes = prepare_shapes(2)
  for i, shape_idx in enumerate(nonzero_indices):
    term_key = f'workspace/~/global_stage/~/lv3_term_{i}'
    lv2_key = f'{term_key}/~/lv2_stage'

    term_rp_logits = np.zeros((6, 6), dtype=np.float64)
    # First term region is sufficient to determine size limit
    ver_term_0 = ver_gs.term_ptr[0][shape_idx]
    num_split = ver_term_0.num_split

    term_sd_logits = np.zeros((6, 6, num_split), dtype=np.float64)

    lv2_split_0_logits = np.zeros((6, 6, len(lv2_shapes)), dtype=np.float64)

    for r in range(6):
      ver_term = ver_gs.term_ptr[r][shape_idx]
      term_rp_logits[r] = safe_log(ver_pm.get_param(ver_term.region_prop_id))

      for inner_r in range(6):
        term_sd_logits[r, inner_r] = safe_log(
            ver_pm.get_param(ver_term.split_dist_id[inner_r])
        )

        for split_i in range(num_split):
          for ptr in [
              ver_term.left_ptr[inner_r][split_i],
              ver_term.right_ptr[inner_r][split_i],
          ]:
            if ptr is not None and getattr(ptr, 'split_0_id', None) is not None:
              lv2_idx = np.where((lv2_shapes == ptr.shape).all(axis=1))[0][0]
              if lv2_split_0_logits[r, inner_r, lv2_idx] == 0.0:
                s0 = ver_pm.get_param(ptr.split_0_id).item()
                lv2_split_0_logits[r, inner_r, lv2_idx] = safe_log(
                    s0
                ) - safe_log(1.0 - 2.0 * s0)

    new_params[term_key] = {
        'region_prop': jnp.array(term_rp_logits),
        'split_dist': jnp.array(term_sd_logits),
    }
    new_params[lv2_key] = {
        'split_0': jnp.array(lv2_split_0_logits),
    }

  return new_params


