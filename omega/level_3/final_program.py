def evaluate() -> dict[str, float]:
  """Evaluates the omega value for the default hyperparameters."""
  q = 5.0
  K = 1.0
  num_steps = 32_000
  hyper = get_hyper_sweep()[0]
  num_sinkhorn_iterations = hyper['num_sinkhorn_iterations']
  learning_rate = hyper['learning_rate']
  num_seeds = hyper['num_seeds']
  best_params, _, _ = optimize_omega(
      q=q,
      K=K,
      num_steps=num_steps,
      learning_rate=learning_rate,
      num_sinkhorn_iterations=num_sinkhorn_iterations,
      num_seeds=num_seeds,
  )

  ver_x = convert_params_to_verification(
      best_params, q=q, K=K, num_sinkhorn_iterations=num_sinkhorn_iterations
  )
  ver_omega = verification.verify_omega(q=q, K=K, max_level=3, x_vector=ver_x)
  return {'neg_omega': -ver_omega}, {'best_x': ver_x.tolist()}


if __name__ == '__main__':
  scores, _ = evaluate()
  print(f'Verified omega = {-scores["neg_omega"]:.8f}')
