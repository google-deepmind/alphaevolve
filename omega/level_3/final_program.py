def prepare_shapes(level: int) -> np.ndarray:
  """Enumerates all 3-part compositions of 2**level."""
  sum_col = 2**level
  shapes = []
  for i in range(sum_col + 1):
    for j in range(sum_col - i + 1):
      k = sum_col - i - j
      shapes.append((i, j, k))
  return np.array(shapes, dtype=int)


def prepare_splits(
    shape: Sequence[int] | jax.Array,
) -> np.ndarray:
  """Enumerates all ways to split a shape into two halves."""
  shape = np.asarray(shape, dtype=int)
  sum_col = int(np.sum(shape))
  sum_half = sum_col // 2
  splits = []
  for i in range(min(sum_half, shape[0]) + 1):
    for j in range(min(sum_half - i, shape[1]) + 1):
      k = sum_half - i - j
      if k > shape[2]:
        continue
      splits.append((i, j, k, shape[0] - i, shape[1] - j, shape[2] - k))
  return np.array(splits, dtype=int)


def joint_to_margin(
    column: np.ndarray | jax.Array, sum_col: int
) -> jnp.ndarray:
  """Builds indicator matrices mapping joint states to per-dimension marginals."""
  n_col = column.shape[0]
  rows = np.arange(n_col)
  mat = jnp.zeros((3, n_col, sum_col + 1), dtype=float)
  for dim in range(3):
    mat = mat.at[dim, rows, column[:, dim]].set(1.0)
  return mat


def marginal_dist(
    alph: jax.Array,
    joint_to_margin_mats: jax.Array,
) -> jnp.ndarray:
  """Computes per-dimension marginal distributions from a joint distribution."""
  return jnp.einsum('s,dsm->dm', alph, joint_to_margin_mats)


def _solve_max_entropy_sinkhorn(
    target_dist: jax.Array,
    joint_to_margin_mats: jax.Array,
    num_iterations: int,
) -> tuple[jax.Array, jax.Array, jax.Array]:
  """Solves for the max-entropy distribution via iterated Sinkhorn scaling."""
  num_dims, _, num_marginals = joint_to_margin_mats.shape
  assert num_dims == 3, f'Expected 3 dimensions, got {num_dims}.'
  target_marginals = marginal_dist(target_dist, joint_to_margin_mats)
  valid_mask = target_marginals > 1e-16

  def body_fn(
      i: int, state: tuple[jax.Array, jax.Array, jax.Array]
  ) -> tuple[jax.Array, jax.Array, jax.Array]:
    del i
    probs, lam_margin, lam_sum = state
    for d in range(num_dims):
      m = jnp.einsum('s,sm->m', probs, joint_to_margin_mats[d])
      safe_m = jnp.where(valid_mask[d], m, 1.0)
      ratio = jnp.where(valid_mask[d], target_marginals[d] / safe_m, 1.0)
      probs = probs * jnp.einsum('m,sm->s', ratio, joint_to_margin_mats[d])
      lam_margin = lam_margin.at[d].add(jnp.log(jnp.maximum(ratio, 1e-12)))
      sum_probs = jnp.sum(probs)
      probs = probs / sum_probs
      lam_sum -= jnp.log(jnp.maximum(sum_probs, 1e-12))
    return probs, lam_margin, lam_sum

  p_init = jnp.ones_like(target_dist, dtype=jnp.float64) / target_dist.size
  lam_margin_init = jnp.zeros((num_dims, num_marginals), dtype=jnp.float64)
  lam_sum_init = jnp.array(1.0 - jnp.log(target_dist.size), dtype=jnp.float64)
  state_init = (p_init, lam_margin_init, lam_sum_init)

  return jax.lax.fori_loop(0, num_iterations, body_fn, state_init)


def rot3(
    vec: jax.Array, n: jax.Array = jnp.array(1, dtype=jnp.int32)
) -> jax.Array:
  """Cyclically rotates a 3-element vector by n positions."""
  assert vec.shape[0] == 3
  return jnp.roll(vec, shift=-n, axis=0)


def encode_csd(arr: Sequence[int] | np.ndarray) -> int:
  """Encodes a ternary array into a 1-based integer index."""
  arr = list(arr)
  val = 0
  for a in arr:
    val = val * 3 + int(a)
  return val + 1


def decode_csd(idx: int, power: int) -> np.ndarray:
  """Decodes a 1-based integer index into a ternary array."""
  arr = [0] * power
  val = idx - 1
  for i in range(power - 1, -1, -1):
    arr[i] = val % 3
    val //= 3
  return np.array(arr, dtype=int)


def concat_csd(lhs: jnp.ndarray, rhs: jnp.ndarray) -> jnp.ndarray:
  """Concatenates two complete split distributions via Kronecker product."""
  return jnp.kron(lhs, rhs)


