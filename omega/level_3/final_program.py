class GlobalStage(hk.Module):
  """Global stage for level=3."""

  def __init__(
      self,
      q: float,
      K: float,
      num_sinkhorn_iterations: int,
      name: str = 'global_stage',
  ):
    super().__init__(name=name)
    self.q = q
    self.K = K
    self.num_sinkhorn_iterations = num_sinkhorn_iterations
    self.level = _MAX_LEVEL
    self.power = 2 ** (self.level - 1)
    self.sum_col = 2**self.level
    self.shapes = prepare_shapes(self.level)
    self.num_shape = self.shapes.shape[0]
    self.joint_to_margin_mats = joint_to_margin(self.shapes, self.sum_col)

    nonzero_mask = np.min(self.shapes, axis=1) > 0
    self.nonzero_indices = np.where(nonzero_mask)[0]
    self.zero_indices = np.where(~nonzero_mask)[0]

    self.lv3_zero = Lv3ZeroStage()
    self.lv3_terms = []
    for idx_in_nonzero, shape_idx in enumerate(self.nonzero_indices):
      self.lv3_terms.append(
          Lv3TermInfo(
              self.shapes[shape_idx],
              num_sinkhorn_iterations=self.num_sinkhorn_iterations,
              name=f'lv3_term_{idx_in_nonzero}',
          )
      )

    self.complete_split: jax.Array | None = None

  def __call__(self):
    self.region_prop = special.softmax(
        hk.get_parameter(
            'region_prop',
            [6],
            init=hk.initializers.RandomUniform(-1.0, 1.0),
        )
    )
    self.dist = jax.vmap(special.softmax)(
        hk.get_parameter(
            'dist',
            [6, self.num_shape],
            init=hk.initializers.RandomUniform(-1.0, 1.0),
        )
    )
    self.dist_max, self.lam_margin, self.lam_sum = jax.vmap(
        _solve_max_entropy_sinkhorn, in_axes=(0, None, None)
    )(self.dist, self.joint_to_margin_mats, self.num_sinkhorn_iterations)

    all_derivatives = [self._get_derivatives(r) for r in range(6)]
    self.derivative_upper_bound = jnp.stack(
        [jnp.max(jnp.abs(d)) for d in all_derivatives]
    )
    self.mean_sq_derivatives = jnp.stack(
        [jnp.mean(d**2) for d in all_derivatives]
    )

    self.lv3_zero()
    for term in self.lv3_terms:
      term()

  def _get_derivatives(self, r):
    return (
        self.lam_margin[r][0][self.shapes[:, 0]]
        + self.lam_margin[r][1][self.shapes[:, 1]]
        + self.lam_margin[r][2][self.shapes[:, 2]]
        + self.lam_sum[r]
        - 1.0
        - jnp.log(self.dist_max[r])
    )

  def evaluate_pre(self):
    for i, term in enumerate(self.lv3_terms):
      shape_idx = self.nonzero_indices[i]
      term.term_frac = self.dist[:, shape_idx] * self.region_prop
    self.lv3_zero.term_frac = (
        self.dist[:, self.zero_indices] * self.region_prop[:, None]
    )
    for term in self.lv3_terms:
      term.evaluate_pre()

  def evaluate_post(self, log_q: float):
    del log_q  # Unused.
    self.hash_penalty_term = (
        jax.vmap(entropy)(self.dist_max)
        - jax.vmap(entropy)(self.dist)
        + 2 * self.derivative_upper_bound
    ) * self.region_prop
    all_dists = jax.vmap(marginal_dist, in_axes=(0, None))(
        self.dist, self.joint_to_margin_mats
    )
    all_ent = jax.vmap(jax.vmap(entropy))(all_dists)
    self.num_block = all_ent * self.region_prop[:, None]

    self.mat_size = jnp.zeros(3)
    for term in self.lv3_terms:
      self.mat_size = self.mat_size + jnp.sum(
          term.lv2.mat_size_contribution, axis=(0, 1, 2)
      )
    self.mat_size = self.mat_size + jnp.sum(
        self.lv3_zero.mat_size_contribution, axis=(0, 1)
    )

    self.complete_split = jnp.zeros((6, 3, 3**self.power))
    for i, term in enumerate(self.lv3_terms):
      shape_idx = self.nonzero_indices[i]
      self.complete_split += jnp.einsum(
          'r,rtc->rtc', self.dist[:, shape_idx], term.complete_split
      )
    self.complete_split += jnp.einsum(
        'rz,rztc->rtc',
        self.dist[:, self.zero_indices],
        self.lv3_zero.complete_split,
    )

    all_cs = self._build_all_cs()

    dims_y = _DIMS[:, 1]
    dims_z = _DIMS[:, 2]

    cs_ent = jax.vmap(jax.vmap(entropy))(self.complete_split)
    pz_den = cs_ent[np.arange(6), dims_z] - all_ent[np.arange(6), dims_z]
    py_den = cs_ent[np.arange(6), dims_y] - all_ent[np.arange(6), dims_y]

    has_zero = np.min(self.shapes, axis=1) == 0

    pz_num = self._gs_pcomp_numerator(all_cs, dims_z, None, has_zero)
    py_num = self._gs_pcomp_numerator(all_cs, dims_y, dims_z, None)

    self.p_compZ = (pz_num - pz_den) * self.region_prop
    self.p_compY = (py_num - py_den) * self.region_prop

  def _build_all_cs(self):
    vec_size = 3**self.power
    all_cs = jnp.zeros((6, self.num_shape, 3, vec_size))
    for i, term in enumerate(self.lv3_terms):
      shape_idx = self.nonzero_indices[i]
      all_cs = all_cs.at[:, shape_idx].set(term.complete_split)
    for j, shape_idx in enumerate(self.zero_indices):
      all_cs = all_cs.at[:, shape_idx].set(self.lv3_zero.complete_split[:, j])
    return all_cs

  def _gs_pcomp_numerator(
      self,
      all_cs: jax.Array,
      target_dims: np.ndarray,
      entropy_dims: np.ndarray | None,
      has_zero: np.ndarray | None,
  ):
    n_groups = self.sum_col + 1
    eps = jnp.finfo(float).eps

    shape_target_size = self.shapes[:, target_dims].T
    active = shape_target_size > 0

    if entropy_dims is None:
      assert has_zero is not None
      use_ent = np.broadcast_to(has_zero, (6, self.num_shape))
    else:
      use_ent = self.shapes[:, entropy_dims].T == 0

    ent_mask = active & use_ent
    acc_mask = active & ~use_ent

    target_one_hot = jax.nn.one_hot(target_dims, 3)
    cs_target = jnp.einsum('rstv,rt->rsv', all_cs, target_one_hot)

    ent_vals = jax.vmap(jax.vmap(entropy))(cs_target)
    masked_dist_ent = self.dist * jnp.array(ent_mask)
    res = jnp.sum(masked_dist_ent * ent_vals, axis=1)

    masked_dist_acc = self.dist * jnp.array(acc_mask)
    contributions = masked_dist_acc[:, :, None] * cs_target

    group_one_hot = jax.nn.one_hot(shape_target_size, n_groups)
    weighted = jnp.einsum('rsv,rsg->grv', contributions, group_one_hot)
    prob_sum = jnp.einsum('rs,rsg->gr', masked_dist_acc, group_one_hot)

    w = jnp.clip(weighted[1:], 0.0, None)
    p = prob_sum[1:]
    mask = p > 0
    safe_p = jnp.where(mask, p, 1.0)
    safe_w = jnp.where(mask[..., None], w, 1.0)
    normalized = safe_w / safe_p[..., None]
    safe_normalized = jnp.maximum(normalized, eps)
    group_ent = jnp.sum(-safe_w * jnp.log(safe_normalized), axis=-1)
    group_ent = jnp.where(mask, group_ent, 0.0)
    res = res + jnp.sum(group_ent, axis=0)
    return res


